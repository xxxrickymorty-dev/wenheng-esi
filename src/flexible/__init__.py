"""灵活报告（第二条产线）——按问题产出分析稿，与复刻报告共用同一份数据底座。

设计权威口径：`评审文档/19-双模式报告设计方案v1（权威口径）-20260920.md`
实施交接：`评审文档/20-交接_代码agent（灵活报告实现）-20260920.md`

🔴 三条不可违反的红线（代码里各有落点）：

1. **复刻报告一个字节都不许变**。本包**只读** `out/<期次>/`，不 import 任何写路径；
   对 `charts.py` 的改动仅限「追加可选参数、默认值＝原行为」。
2. **LLM 的输出类型里不允许存在「数字」**。数字唯一路径＝
   `queries` 发结构化查询 → 工具从 parquet 取值 → 回填骨架空位。
   `planner` 拿不到任何数值，只能选科/选指/选期。
3. **AI 不得指定图表纵轴范围**。`spec` 只接受 `invert` / `include` / `zero_base` 这类
   **语义**参数，没有「上下界」这个字段（`spec.py` 有结构断言）。

模块分工：

| 文件 | 职责 |
|---|---|
| `datasource.py` | 只读数据访问 + **来源链**（每个数字指回台账工作表与期次列） |
| `queries.py` | 4 个数据查询工具（LLM 拿数的唯一入口，白名单 schema） |
| `summary.py` | 统计摘要 + 异常检测（**规则实现**，标记为「规划依据」而非「可引用数值」） |
| `spec.py` | 图表声明语言 → 复用 `charts.py` 排版设施渲染 |
| `opinion.py` | 三级判断分级（描述性/解释性/专业判断） |
| `planner.py` | 章节规划；`rule` 后端为默认，无 LLM 也能出完整计划 |
| `report.py` | 编排：规划 → 查询 → 数字回填骨架 → spec 出图 → 产出 md |
"""

