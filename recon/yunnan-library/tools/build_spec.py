def hex_to_rgba(value: str, alpha: float = 1.0) -> str:
    value = value.lstrip("#")
    r, g, b = int(value[0:2], 16), int(value[2:4], 16), int(value[4:6], 16)
    return f"rgba({r}, {g}, {b}, {alpha})"


def add_color_material_recipe(c: dict) -> None:
    mid = c.get("material") or ""
    pair = MATERIAL_HEX.get(mid)
    if not pair:
        return
    dominant, secondaries = pair
    c["colorMaterialRecipe"] = {
        "dominantAlbedo": hex_to_rgba(dominant),
        "secondaryAlbedo": hex_to_rgba(secondaries[0]),
        "materialClass": MATERIAL_CLASS.get(mid, "unknown"),
        "materialClassConfidence": 0.8,
    }


def comp(
    cid: str,
    name: str,
    level: str,
    parent: str | None,
    pos,
    dims,
    material: str,
    *,
    role: str = "structure",
    primitive: str = "box",
    topology: str = "assembled-solid",
    topo_reason: str = "Discrete rigid mass with flat faces; genuinely built from a box.",
    rot=(0.0, 0.0, 0.0),
    att: dict | None = None,
    features: list[dict] | None = None,
    evidence: list[str] | None = None,
    importance: float = 0.7,
    confidence: float = 0.8,
    descriptor: dict | None = None,
    anim_role: str = "static-part",
    notes: str = "",
):
    descriptor_full = {
        "topologyIntent": notes or "authored architectural mass",
        "edgeTreatment": edge_treatment(),
        "deformationStack": [],
        "uvStrategy": "generated procedural coordinates",
        "normalStrategy": "vertex normals from generated geometry",
    }
    if descriptor:
        descriptor_full.update(descriptor)
    return {
        "id": cid,
        "name": name,
        "level": level,
        "role": role,
        "importance": importance,
        "confidence": confidence,
        "primitive": primitive,
        "topologyClass": topology,
        "topologyRationale": topo_reason,
        "geometryDescriptor": descriptor_full,
        "parent": parent,
        "attachment": att,
        "dimensions": {
            "width": dims[0],
            "height": dims[1],
            "depth": dims[2],
            "units": "relative",
            "confidence": confidence,
        },
        "transform": transform(pos, rot),
        "actionProfile": {
            "animationRole": anim_role,
            "pivot": {"mode": "center", "localPosition": [0, 0, 0], "axis": [0, 1, 0], "confidence": confidence},
            "transformChannels": {
                "translate": True, "rotate": True, "scale": True,
                "bend": False, "twist": False, "detach": True,
                "visibility": True, "materialState": True,
            },
            "sockets": [],
            "collider": {
                "type": "box",
                "offset": [0, 0, 0],
                # unit-box proxy in the component's own parametric frame; runtime may
                # swap in compound proxies. Kept conservative on purpose.
                "scale": [1, 1, 1],
                "isTrigger": False,
                "notes": "",
            },
            "constraints": [],
            "destruction": {
                "breakable": False,
                "fractureGroup": cid,
                "seamRefs": [],
                "detachableFragments": [],
                "breakImpulse": 0.0,
                "debrisMaterial": material,
            },
        },
        "material": material,
        "materialLayers": [material],
        "deformations": [],
        "joints": [],
        "seams": [],
        "localFeatures": features or [],
        "surfaceDetail": {
            "macroRoughness": 0.35, "microRoughness": 0.12, "bumpAmplitude": 0.05,
            "normalPattern": "", "displacementPattern": "", "occlusionPattern": "",
            "edgeWearPattern": "", "notes": "",
        },
        "evidenceRefs": evidence or ["view:front-elevation"],
        "details": [],
        "fidelityTier": "blockout" if level == "macro" else "structure",
    }


def feature(fid: str, description: str) -> dict:
    return {"id": fid, "description": description}


