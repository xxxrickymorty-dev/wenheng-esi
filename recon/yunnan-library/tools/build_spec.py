def mat(
    mid: str,
    name: str,
    color: str,
    secondary,
    rough: float,
    metal: float,
    *,
    variation: float = 0.12,
    pattern: str = "mottled",
    bands=None,
    overrides=None,
    extra=None,
    tex_res: int = 1024,
    note: str = "",
):
    base = {
        "id": mid,
        "name": name,
        "type": "standard",
        "shaderModel": "MeshPhysicalMaterial / PBR approximation",
        "baseColor": color,
        "color": color,
        "albedo": {
            "dominant": color,
            "secondary": list(secondary),
            "samplingNotes": note or "Sampled from the reference views; near-flat painted/stone surfaces read as solid albedo.",
        },
        "colorVariation": {
            "palette": [color, *secondary],
            "pattern": pattern,
            "amplitude": variation,
            "heightCorrelation": 0.2,
        },
        "textureResolution": tex_res,
        "textureProjection": {
            "mode": "uv",
            "repeat": [3.0, 3.0],
            "anisotropy": 8,
            "texelDensityIntent": "stable world-scale detail; no stretching with component scale",
        },
        "surfaceFrequencyBands": bands or [
            {"id": "macro", "frequency": 2.0, "amplitude": 0.3, "role": "broad tone breakup"},
            {"id": "meso", "frequency": 12.0, "amplitude": 0.16, "role": "visible relief: courses, grain, ribs"},
            {"id": "micro", "frequency": 56.0, "amplitude": 0.06, "role": "highlight breakup at grazing light"},
        ],
        "roughness": {
            "base": rough,
            "variation": round(min(0.5, variation + 0.05), 3),
            "map": "independent-procedural-field",
            "localResponse": "slightly higher roughness in cavities; lower on worn/polished edges",
        },
        "metalness": {"base": metal, "variation": 0.0 if metal == 0 else 0.05},
        "normal": {"pattern": "derived-from-independent-height-field", "strength": 0.3, "scale": 20.0, "space": "tangent"},
        "bump": {"pattern": "procedural-noise", "amplitude": 0.04, "scale": 1.0},
        "displacement": {"pattern": "none", "amplitude": 0.0, "scale": 1.0, "silhouetteAffects": False},
        "ambientOcclusion": {"cavityStrength": 0.28, "contactShadowBias": 0.4, "notes": "darken seams and recesses"},
        "wear": {"edgeWear": 0.05, "scratches": [], "chips": []},
        "dirt": {"amount": 0.05, "cavityBias": 0.6, "color": "#3A322A"},
        "localOverrides": overrides or [],
        "shaderNotes": [
            "Generate albedo, roughness, height/normal, and AO independently; never alias albedo into roughness.",
            "Reference-derived scalars carried from the four supplied views; runtime maps are procedural canvases.",
        ],
        "notes": note,
    }
    if extra:
        base.update(extra)
    return base


def override(oid: str, region: str, changes: dict, evidence: str) -> dict:
    return {"id": oid, "region": region, "changes": changes, "evidenceRef": evidence, "confidence": 0.8}


